"""Lower bounds from symmetric configurations.
Pick a cyclic subgroup H of the affine symmetry group of the beta family,
generated by one element g (acting on incidences (a, x)); restrict to
H-invariant supports, i.e. one Boolean per H-orbit of incidences, and solve the
reduced problem with CP-SAT. Any solution is a genuine configuration (it is
expanded and re-checked with check_simple.py).

Group elements (verified against the clause set below):
  a2  : r -> (a, x) |-> (r a, r x)          [(x,y) -> (r x, r^2 y)]
  a3  : r -> (a, x) |-> (r a, r^2 x)        [(x,y) -> (r^2 x, r^3 y)]
  inv : r -> (a, x) |-> (a / r, r^2 x)      [(x,y) -> (r^2 x, r y)]
  zero: (s, u) -> (a, x) |-> (u a / s, s x) [(x,y) -> (s x, u y)]
usage: sym_solve.py beta p h time_limit [j]
  h = order of H (divides p - 1); for zero, H = <(g^k, g^(k j))>, k = (p-1)/h.
"""
import sys, json, time
from ortools.sat.python import cp_model
from model import build, var, unvar, edges_of
from check_simple import check, affine_to_graph


def primroot(p):
    fac = [q for q in range(2, p) if (p - 1) % q == 0 and all(q % r for r in range(2, q))]
    for g in range(2, p):
        if all(pow(g, (p - 1) // q, p) != 1 for q in fac):
            return g


def gen_map(beta, p, h, j=1):
    g = primroot(p)
    k = (p - 1) // h
    r = pow(g, k, p)
    ri = pow(r, p - 2, p)
    if beta == 'a2':
        f = lambda a, x: (r * a % p, r * x % p)
    elif beta == 'a3':
        f = lambda a, x: (r * a % p, r * r * x % p)
    elif beta == 'inv':
        f = lambda a, x: (a * ri % p, r * r * x % p)
    else:
        s, u = r, pow(r, j, p)
        f = lambda a, x: (u * a * pow(s, p - 2, p) % p, s * x % p)
    return lambda v: var(*f(*unvar(v, p)), p)


def solve(beta, p, h, tl, j=1, workers=4, hint=None):
    B, simp, cyc = build(p, beta)
    nv = (p - 1) * p
    g = gen_map(beta, p, h, j)
    perm = [g(v) for v in range(nv)]
    # check that g is a symmetry of the constraint system
    cs = set(map(frozenset, cyc)) | set(map(frozenset, simp))
    for c in cs:
        assert frozenset(perm[v] for v in c) in cs
    orb = [-1] * nv
    sizes = []
    for v in range(nv):
        if orb[v] < 0:
            o = len(sizes)
            w, n = v, 0
            while orb[w] < 0:
                orb[w] = o
                w = perm[w]
                n += 1
            sizes.append(n)
    no = len(sizes)
    red = set()
    banned = set()
    for c in cs:
        oc = frozenset(orb[v] for v in c)
        if len(oc) == 1:
            banned |= oc
        red.add(oc)
    M = cp_model.CpModel()
    Y = [M.new_bool_var('o%d' % o) for o in range(no)]
    for o in banned:
        M.add(Y[o] == 0)
    for oc in red:
        if len(oc) > 1:
            M.add_bool_or([Y[o].Not() for o in oc])
    M.maximize(sum(sizes[o] * Y[o] for o in range(no)))
    if hint is not None:
        for o in range(no):
            M.add_hint(Y[o], o in hint)
    S = cp_model.CpSolver()
    S.parameters.max_time_in_seconds = tl
    S.parameters.num_workers = workers
    t0 = time.time()
    st = S.solve(M)
    sol = [v for v in range(nv) if S.value(Y[orb[v]])]
    n, G = affine_to_graph(p, edges_of(sol, p, B))
    ok, info = check(n, G)
    assert ok, info
    return dict(beta=beta, p=p, h=h, j=j, m=len(sol), sym_ub=int(S.best_objective_bound + 1e-6),
                status=S.status_name(st), time=time.time() - t0, norbits=no, sol=sol)


if __name__ == '__main__':
    beta, p, h, tl = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), float(sys.argv[4])
    j = int(sys.argv[5]) if len(sys.argv) > 5 else 1
    r = solve(beta, p, h, tl, j, workers=1)
    print(json.dumps({k: v for k, v in r.items() if k != 'sol'}), flush=True)
    import os
    os.makedirs('runs', exist_ok=True)
    json.dump(r, open('runs/sym_%s_%d_h%d_j%d.json' % (beta, p, h, j), 'w'))
